def _existing_keys(conn) -> set:
    with conn.cursor() as cur:
        cur.execute("SELECT title, meeting_date FROM meetings")
        return {(r[0], str(r[1]) if r[1] else None) for r in cur.fetchall()}


def main():
    conn = get_connection()
    clova = ClovaStudioClient()
    try:
        existing = _existing_keys(conn)
        added = skipped = 0
        for m in SAMPLE_MEETINGS:
            if (m["title"], m["meeting_date"]) in existing:
                print(f"건너뜀(이미 있음): {m['title']} ({m['meeting_date']})")
                skipped += 1
                continue
            mid = ingest_meeting(
                conn, clova, m["title"], m["meeting_date"], m["attendees"], m["raw_text"]
            )
            print(f"적재 완료: {m['title']} ({m['meeting_date']}) id={mid}")
            added += 1
        print(f"\n완료 — 적재 {added}건 / 건너뜀 {skipped}건 / 전체 후보 {len(SAMPLE_MEETINGS)}건")
    finally:
        conn.close()


if __name__ == "__main__":
    main()
